"""Relationship energy and moods as the app ranks them (scoring revision 2).

The golden fixtures are generated by the app (Auralscape
``src/lib/__tests__/album_dynamics_energy_golden.json`` and
``album_dynamics_mood_golden.json``); copy them again when the app's
calibration or Album Dynamics method changes.
"""

import json
from pathlib import Path

import pytest

from test_lumae_analysis import load_plugin, lumae_postgres_db  # noqa: F401 (stubs plugin.api)
from plugins.LumaeAnalysis import catalog, catalog_enrichment as e
from plugins.LumaeAnalysis import sonic_calibration as sc

HERE = Path(__file__).resolve().parent
ENERGY_GOLDEN = json.loads((HERE / "album_dynamics_energy_golden.json").read_text(encoding="utf-8"))
MOOD_GOLDEN = json.loads((HERE / "album_dynamics_mood_golden.json").read_text(encoding="utf-8"))

# p5, p25, p50, p75 and p95 of the owner's library's raw energy (AudioMuse
# v3.4.0 formula, 36,752 songs, 2026-10-30).
OWNER_LIBRARY_QUANTILES = [0.5303, 0.6824, 0.7369, 0.7737, 0.8118]


def test_the_vendored_tables_are_the_fixtures_calibration():
    assert sc.CALIBRATION_VERSION == "sonic-calibration-v2"
    assert ENERGY_GOLDEN["calibrationVersion"] == sc.CALIBRATION_VERSION
    assert MOOD_GOLDEN["calibrationVersion"] == sc.CALIBRATION_VERSION
    assert ENERGY_GOLDEN["method"] == "lumae_album_dynamics_v2"
    assert tuple(MOOD_GOLDEN["moods"]) == sc.MOOD_NAMES
    assert len(sc.ENERGY_V34) == 256
    assert set(sc.MOOD_TABLES) == {"clap", "classifier"}


def test_energy_matches_the_app_golden():
    for song in ENERGY_GOLDEN["songs"]:
        assert sc.normalize_energy(song["raw"], song["scale"]) == song["energy"], song
    for album in ENERGY_GOLDEN["albums"]:
        energies = [sc.normalize_energy(raw, album["scale"]) for raw in album["rawEnergies"]]
        stats = e._range_stats(energies)
        for key, expected in album["energy"].items():
            assert stats[key] == pytest.approx(expected, abs=1e-12), (album["name"], key)


def test_moods_match_the_app_golden():
    for song in MOOD_GOLDEN["songs"]:
        assert sc.mood_ranks(song["otherFeatures"]) == song["slots"], song["case"]
    means = {}
    for album in MOOD_GOLDEN["albums"]:
        stats = e._mood_stats([{"mood": sc.mood_ranks(other)} for other in album["otherFeatures"]])
        assert stats["mean"] == pytest.approx(album["mood"]["mean"], abs=1e-6), album["name"]
        assert stats["min"] == album["mood"]["min"], album["name"]
        assert stats["max"] == album["mood"]["max"], album["name"]
        means[album["name"]] = stats["mean"]
    for pair in MOOD_GOLDEN["pairs"]:
        distance = e._normalize_distance(e._cosine_distance(means[pair["a"]], means[pair["b"]]))
        assert distance == pytest.approx(pair["moodDistance"], abs=1e-6), pair


def test_moods_read_a_dict_payload_and_default_to_zero():
    assert sc.mood_ranks(None) == [0.0] * 6
    assert sc.mood_ranks("") == [0.0] * 6
    assert sc.mood_ranks({"happy": 0.62, "sad": "0.58"}) == sc.mood_ranks("happy:0.62,sad:0.58")


def test_a_v34_library_ranks_through_the_fixed_table():
    library = [0.5 + index / 1000 for index in range(100)]
    assert sc.energy_scale(library) == {"kind": "v34"}
    ranked = [sc.normalize_energy(raw, {"kind": "v34"}) for raw in OWNER_LIBRARY_QUANTILES]
    # Revision 1's fixed 0.01-0.15 window put every one of these at 1.
    assert [max(0.0, min(1.0, (raw - 0.01) / 0.14)) for raw in OWNER_LIBRARY_QUANTILES] == [1.0] * 5
    assert ranked == sorted(ranked)
    assert ranked[0] < 0.1 and 0.4 < ranked[2] < 0.6 and 0.9 < ranked[4] < 1


def test_an_old_formula_library_maps_against_its_own_p5_and_p95():
    library = [index / 100 for index in range(1, 41)]  # 0.01 .. 0.40, median 0.21
    scale = sc.energy_scale(library)
    # floor(40 * 0.05) = 2 and floor(40 * 0.95) = 38, as the app's OFFSET reads.
    assert scale == {"kind": "range", "min": 0.03, "max": 0.39}
    assert sc.normalize_energy(0.21, scale) == pytest.approx(0.5)
    assert sc.normalize_energy(0.01, scale) == 0.0
    assert sc.normalize_energy(0.5, scale) == 1.0


def test_a_small_or_flat_library_keeps_the_theoretical_window():
    assert sc.energy_scale([0.7] * 19 + [None]) == sc.FALLBACK_ENERGY_SCALE
    assert sc.energy_scale([0.1] * 40) == sc.FALLBACK_ENERGY_SCALE
    assert sc.normalize_energy(None, {"kind": "v34"}) is None
    assert sc.normalize_energy(float("nan"), {"kind": "v34"}) is None
    assert sc.raw_energy("0.74") == 0.74
    assert sc.raw_energy("nan") is None
    assert sc.raw_energy(None) is None


class _Cursor:
    def __init__(self, rows):
        self.rows = rows

    def execute(self, *_args):
        pass

    def fetchall(self):
        return self.rows


def _row(track_id, album, energy, other_features, *, embedding=True):
    vector = bytes(4 * 2) if not embedding else b"\x00\x00\x80?" + b"\x00\x00\x00\x00"
    scalar = {"energy": energy, "other_features": other_features, "mood_vector": "happy:0.73"}
    return (track_id, f"album-{album}", album, "Artist", "Artist", 1, 1, None, "{}", None,
            json.dumps(scalar), vector if embedding else b"", 2)


def test_relationship_inputs_rank_energy_on_the_library_scale_and_moods_as_ranks():
    rows = [
        _row(f"t{index}", "Album", 0.5 + index / 100, "danceable:0.61,aggressive:0.61,happy:0.62,"
             "party:0.62,relaxed:0.57,sad:0.58")
        for index in range(30)
    ]
    # Genre tags named like moods (mood_vector "happy:0.73") never stand in.
    rows.append(_row("t-tags", "Album", 0.7, None))
    # Analysed but without a vector: not a relationship input, still part of the scale.
    rows.append(_row("t-novector", "Album", 0.95, None, embedding=False))
    tracks = e._load_relationship_inputs(_Cursor(rows), {
        "catalog_instance_id": "catalog-a",
        "catalog": {"generation": 1},
        "analysis": {"generation": 1},
    })

    assert [track["id"] for track in tracks] == [f"t{index}" for index in range(30)] + ["t-tags"]
    assert tracks[0]["energy"] == sc.rank_of(sc.ENERGY_V34, 0.5)
    assert tracks[29]["energy"] == sc.rank_of(sc.ENERGY_V34, 0.79)
    assert 0 < tracks[0]["energy"] < tracks[29]["energy"] < 1
    assert tracks[0]["mood"] == MOOD_GOLDEN["songs"][0]["slots"]
    assert tracks[-1]["mood"] == [0.0] * 6


def test_energy_separates_otherwise_identical_albums():
    def album(key, raws):
        tracks = [
            {"id": f"{key}{index}", "embedding": [1.0, index * 0.1], "order": index,
             "energy": sc.normalize_energy(raw, {"kind": "v34"}), "mood": [0.5] * 6,
             "album": key, "year": 2020}
            for index, raw in enumerate(raws)
        ]
        return {"key": key, "album": key, "artist": key, "cover": f"{key}0",
                "fingerprint": e._album_fingerprint(key, tracks)}

    source = album("source", [0.66, 0.7, 0.74, 0.76])
    louder = album("aardvark", [0.8, 0.81, 0.82, 0.83])
    matching = album("zebra", [0.67, 0.7, 0.73, 0.77])

    ranked = e._rank_albums(source, [source, louder, matching])

    assert [row["albumKey"] for row in ranked] == ["zebra", "aardvark"]


@pytest.mark.parametrize("revision, queued", [(1, True), (2, False)])
def test_complete_relationships_of_an_older_scoring_revision_are_rebuilt(
    monkeypatch, revision, queued
):
    mod = load_plugin()
    source = {
        "catalog_instance_id": "catalog-a",
        "server_id": "server-a",
        "catalog": {"generation": 4},
        "analysis": {"generation": 5},
    }
    monkeypatch.setattr(mod, "get_db", lambda: object())
    monkeypatch.setattr(mod, "resolve_profile_source", lambda **_kwargs: source)
    monkeypatch.setattr(mod, "relationship_status", lambda *_args: {
        "status": "complete",
        "source_catalog_generation": 4,
        "source_analysis_generation": 5,
        "schema_version": mod.RELATIONSHIP_SCHEMA_VERSION,
        "algorithm_version": mod.RELATIONSHIP_ALGORITHM_VERSION,
        "scoring_revision": revision,
    })
    monkeypatch.setattr(mod, "claim_relationship_preparation", lambda *_args, **_kwargs: True)

    result = mod.start_relationship_preparation("catalog-a", "server-a")

    assert result["queued"] is queued
    assert mod.RELATIONSHIP_SCORING_REVISION == 2


def test_postgres_published_revision_1_relationships_turn_stale(  # noqa: F811
    lumae_postgres_db, monkeypatch
):
    db = lumae_postgres_db
    catalog.migrate_catalog(db)
    cur = db.cursor()
    cur.execute(
        """
        INSERT INTO plugin_lumae_analysis__catalog_sources
            (catalog_instance_id, current_core_server_id, provider_type, server_name)
        VALUES ('catalog-a', 'server-a', 'navidrome', 'Main source')
        """
    )
    cur.close()
    e.migrate_enrichment(db)

    def state():
        cur = db.cursor()
        cur.execute(
            """
            SELECT algorithm_version, scoring_revision, result_generation, status
              FROM plugin_lumae_analysis__relationship_state
             WHERE catalog_instance_id='catalog-a'
            """
        )
        row = cur.fetchone()
        cur.close()
        return row

    # A new source starts on the current revision.
    assert state() == (1, e.RELATIONSHIP_SCORING_REVISION, 0, "not_initialized")

    # Published by 1.9.1: the column's default says revision 1.
    cur = db.cursor()
    cur.execute(
        """
        UPDATE plugin_lumae_analysis__relationship_state
           SET scoring_revision=1, result_generation=5, status='complete'
         WHERE catalog_instance_id='catalog-a'
        """
    )
    cur.close()
    db.commit()

    e.migrate_enrichment(db)

    # Still served (and still algorithm 1 on the stream) until the rebuild.
    assert state() == (1, 1, 5, "stale")
    monkeypatch.setattr(e, "resolve_catalog_source", lambda *_args, **_kwargs: [{}])
    status = e.relationship_status(db, "catalog-a")
    assert (status["algorithm_version"], status["scoring_revision"]) == (1, 1)
