def jellyfin_raw_catalog(track_labels=("one", "two"), album="album", library=LIB_A, extra=None):
    """A raw Jellyfin catalogue as ``jellyfin_provider.fetch_catalog`` returns it."""
    from plugins.LumaeAnalysis import jellyfin_provider

    tracks = [
        jellyfin_provider.track_row(
            jellyfin_track_item(label, album, index=index + 1,
                                extra=(extra or {}).get(label)), [library])
        for index, label in enumerate(track_labels)
    ]
    albums = [jellyfin_provider.album_row(jellyfin_album_item(album), [library])]
    return {
        "libraries": [{"id": library, "name": "Music"}],
        "albums": albums,
        "tracks": tracks,
        "artist_cover_art": {jid("artist:Artist"): jid("artist:Artist")},
    }


class JellyfinBridge:
    """A credential-free bridge double for one Jellyfin AudioMuse server."""

    def __init__(self, raw, server_id=SERVER_A, version="12.2.0", product="Jellyfin Server",
                 server_type="jellyfin", core=None):
        self.raw = raw
        self.identity = {
            "provider_type": server_type,
            "server_type": server_type,
            "server_version": version,
            "server_id": server_id,
            "product_name": product,
        }
        self.server_type = server_type
        self.fetches = 0
        self.probe_error = None
        self.core = core

    def list_servers(self):
        return [self.require_server("server-j")]

    def require_server(self, server_id):
        assert server_id == "server-j"
        return {"server_id": "server-j", "name": "Jelly", "provider_type": self.server_type,
                "is_default": True, "supported": True}

    def fetch_catalog(self, server_id):
        self.fetches += 1
        return copy.deepcopy(self.raw)

    def probe_server_identity(self, server_id):
        if self.probe_error:
            raise self.probe_error
        return dict(self.identity)


