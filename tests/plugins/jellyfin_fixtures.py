class FakeResponse:
    def __init__(self, body, status=200):
        self.body = body
        self.status_code = status
        self.text = body if isinstance(body, str) else ""

    def raise_for_status(self):
        if self.status_code >= 400:
            raise RuntimeError(f"HTTP {self.status_code}")

    def json(self):
        return copy.deepcopy(self.body)

    def close(self):
        pass


class FakeJellyfinHttp:
    """Serves Jellyfin 12.2 answers as measured on a real server (2026-10-06).

    ``/Items`` pages per (ParentId, IncludeItemTypes); ``/Artists`` and
    ``/Artists/AlbumArtists`` per ParentId, listing the MusicArtist items
    credited on that library's tracks (ArtistItems) or as album artists, with
    their image tags from ``artists``; a library in ``forbidden`` answers 401
    with Jellyfin's "not permitted" body, one in ``unknown`` 400.
    ``public`` is one ``/System/Info/Public`` body, or a list of
    ``(status, body)`` answers served in turn.
    """

    def __init__(self, base, libraries, artists=None, public=None, fail_artists=False,
                 forbidden=(), unknown=(), unauthorized=False):
        self.base = base
        self.libraries = libraries  # {library_id: {"Audio": [...], "MusicAlbum": [...]}}
        self.artists = artists or {}  # {artist_id: item}
        self.public = public
        self.fail_artists = fail_artists
        self.forbidden = set(forbidden)
        self.unknown = set(unknown)
        self.unauthorized = unauthorized
        self.calls = []

    def _public(self):
        if isinstance(self.public, list):
            status, body = self.public.pop(0)
            return FakeResponse(body, status)
        return FakeResponse(self.public)

    def _artists(self, library_id, album_artists):
        rows = self.libraries[library_id]
        credited = {}
        for item in rows.get("Audio", []) + rows.get("MusicAlbum", []):
            keys = ("AlbumArtists",) if album_artists else ("ArtistItems",)
            if item.get("Type") == "MusicAlbum" and not album_artists:
                continue
            for key in keys:
                for artist in item.get(key) or []:
                    credited[artist["Id"]] = artist["Name"]
        return [
            self.artists.get(artist_id) or {"Id": artist_id, "Name": name,
                                            "Type": "MusicArtist", "ImageTags": {}}
            for artist_id, name in sorted(credited.items(), key=lambda pair: pair[1])
        ]

    def get(self, url, headers=None, params=None, timeout=None, **_kwargs):
        self.calls.append({"url": url, "headers": dict(headers or {}), "params": dict(params or {}),
                           "timeout": timeout})
        params = params or {}
        if url == f"{self.base}/System/Info/Public":
            return self._public()
        if self.unauthorized:
            return FakeResponse("", 401)
        library_id = params.get("ParentId")
        if library_id in self.forbidden:
            return FakeResponse(
                f"lumae-listener is not permitted to access Library {library_id}.", 401)
        if library_id in self.unknown:
            return FakeResponse("Error processing request.", 400)
        start, limit = int(params["StartIndex"]), int(params["Limit"])
        if url in (f"{self.base}/Artists", f"{self.base}/Artists/AlbumArtists"):
            if self.fail_artists:
                raise RuntimeError("artist lookup failed: http://user:token@host")
            rows = self._artists(library_id, url.endswith("/AlbumArtists"))
            return FakeResponse({"Items": rows[start:start + limit]})
        assert url == f"{self.base}/Items", url
        rows = self.libraries[library_id][params["IncludeItemTypes"]]
        return FakeResponse({"Items": rows[start:start + limit]})


class FakeJellyfinModule:
    """The AudioMuse ``tasks.mediaserver.jellyfin`` surface the reader uses."""

    def __init__(self, http, libraries, target=None, base="http://jellyfin.test:8096",
                 token="server-token"):
        self.requests = http
        self._libraries = libraries
        self._target = target
        self._base = base
        self._token = token

    def list_libraries(self):
        return [dict(row) for row in self._libraries]

    def _get_target_library_ids(self):
        return None if self._target is None else set(self._target)

    def _jellyfin_base_url(self):
        return self._base

    def _jellyfin_headers_from_creds(self):
        return {"Authorization": f'MediaBrowser Token="{self._token}"'}

    def _jellyfin_user_id(self):
        return "user-1"


class FakeCore:
    def __init__(self, servers, modules):
        self.servers = servers
        self.modules = modules
        self.bound = []

    def list_servers(self):
        return list(self.servers)

    def bind(self, server_id):
        self.bound.append(server_id)
        return nullcontext()

    def provider_module(self, provider_type):
        return self.modules[provider_type]


